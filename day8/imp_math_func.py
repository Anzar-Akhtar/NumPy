import numpy as np

arr = np.array([10, 20, 30, 40, 50])

# np.sum():- added all the values of array
sum = np.sum(arr)
# arr.sum() this is shortcut
print(sum)


# np.min():- print the minimum value of the array
min = np.min(arr)
# arr.min():- this is shortcut
print(min)


# np.max():- print the maximum value of the array
max = np.max(arr)
# arr.max():- this is shortcut
print(max)


# np.mean():- print the average value of the array
mean = np.mean(arr)
# arr.mean():- this is shortcut
print(mean)


# np.median():- print the middle value of the array
median = np.median(arr)
# arr.median():- this is shortcut
print(median)


# np.argmin():- print the position of the minimum value of the array
argmin = np.argmin(arr)
# arr.argmin():- this is shortcut
print(argmin)


# np.argmax():- print the position of the maximum value of the array
argmax = np.argmax(arr)
# arr.argmax():- this is shortcut
print(argmax)